"""
RAGAS-Style RAG Evaluation Script
Evaluates the RAG pipeline on two core metrics:
  1. Faithfulness   - Are all claims in the answer supported by the retrieved context?
  2. Context Relevance - Are the retrieved chunks actually relevant to the question?

Usage:
    python evaluate.py

Requirements:
    - Backend must be running: python backend.py
    - At least one PDF must be indexed
    - GROQ_API_KEY must be set in .env

Output:
    - Console table of per-question scores
    - evaluate_results.json with full evaluation data
"""

import os
import json
import requests
from dotenv import load_dotenv
from groq import Groq

load_dotenv()

API_BASE_URL = os.getenv("BACKEND_API_URL", "http://localhost:8000")
GROQ_API_KEY = os.getenv("GROQ_API_KEY")
GROQ_MODEL   = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b")

# ---------------------------------------------------------------------------
# Test Dataset
# Edit these question/answer pairs to match the PDFs you have indexed.
# ---------------------------------------------------------------------------
EVAL_DATASET = [
    {
        "question": "What is the main topic of the uploaded document?",
        "reference_answer": None   # None means LLM-only faithfulness check
    },
    {
        "question": "Summarize the key points of the document.",
        "reference_answer": None
    },
    {
        "question": "What specific numbers or statistics are mentioned?",
        "reference_answer": None
    },
    {
        "question": "Who is the author or organization behind this document?",
        "reference_answer": None
    },
]

FAITHFULNESS_PROMPT = """You are a strict factual evaluator.

Given the following CONTEXT retrieved from a document and an ANSWER generated by an AI:

CONTEXT:
{context}

ANSWER:
{answer}

TASK: Evaluate if every factual claim in the ANSWER is directly supported by the CONTEXT.
- Score 1.0 if ALL claims in the ANSWER are explicitly backed by the CONTEXT.
- Score 0.0 if the ANSWER contains ANY claim not found in the CONTEXT (hallucination).
- Score between 0.0-1.0 proportionally for partial support.

Respond with ONLY a JSON object: {{"score": <float 0.0-1.0>, "reason": "<one sentence>"}}"""

RELEVANCE_PROMPT = """You are a strict relevance evaluator.

Given the following QUESTION and CONTEXT retrieved from a document:

QUESTION:
{question}

CONTEXT:
{context}

TASK: Evaluate how relevant the retrieved CONTEXT is to answering the QUESTION.
- Score 1.0 if the CONTEXT directly contains the information needed to answer the QUESTION.
- Score 0.0 if the CONTEXT is completely unrelated to the QUESTION.
- Score between 0.0-1.0 proportionally for partial relevance.

Respond with ONLY a JSON object: {{"score": <float 0.0-1.0>, "reason": "<one sentence>"}}"""


def call_rag_backend(question: str, k: int = 4) -> dict:
    """Query the RAG backend /ask endpoint."""
    try:
        response = requests.post(
            f"{API_BASE_URL}/ask",
            json={"query": question, "k": k, "groq_api_key": GROQ_API_KEY},
            timeout=60
        )
        if response.status_code == 200:
            return response.json()
        else:
            return {"answer": f"API Error: {response.text}", "sources": []}
    except Exception as e:
        return {"answer": f"Connection error: {str(e)}", "sources": []}


def llm_score(prompt: str, client: Groq) -> tuple[float, str]:
    """Ask the LLM to score with a JSON response and extract score + reason."""
    try:
        resp = client.chat.completions.create(
            model=GROQ_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.0,
            max_tokens=200
        )
        raw = resp.choices[0].message.content.strip()
        # Extract JSON from response
        start = raw.find("{")
        end = raw.rfind("}") + 1
        if start != -1 and end != 0:
            data = json.loads(raw[start:end])
            return float(data.get("score", 0.0)), data.get("reason", "")
        return 0.0, "Could not parse LLM response"
    except Exception as e:
        return 0.0, f"Error: {str(e)}"


def evaluate():
    """Run full RAGAS-style evaluation and print results."""
    client = Groq(api_key=GROQ_API_KEY)

    # Check backend
    try:
        status = requests.get(f"{API_BASE_URL}/status", timeout=5).json()
        if not status.get("is_indexed"):
            print("❌ No documents indexed. Please upload a PDF first via the Streamlit UI or /upload endpoint.")
            return
        print(f"✅ Backend connected. {status['total_chunks']} chunks indexed.")
        print(f"   Reranker: {'ACTIVE (' + status.get('reranker_model', '') + ')' if status.get('reranker_active') else 'disabled'}")
        print(f"   LLM: {status['llm_model']}\n")
    except Exception as e:
        print(f"❌ Cannot reach backend at {API_BASE_URL}: {e}")
        return

    results = []
    faithfulness_total = 0.0
    relevance_total = 0.0

    print(f"{'='*80}")
    print(f"{'Question':<45} {'Faithfulness':>14} {'Relevance':>12}")
    print(f"{'='*80}")

    for item in EVAL_DATASET:
        question = item["question"]

        # Step 1: Get RAG answer
        rag_response = call_rag_backend(question, k=4)
        answer = rag_response.get("answer", "")
        sources = rag_response.get("sources", [])

        if not sources:
            print(f"  {question[:44]:<44}  {'N/A':>14} {'N/A':>12}  (no sources retrieved)")
            results.append({
                "question": question,
                "answer": answer,
                "faithfulness_score": None,
                "relevance_score": None,
                "note": "No sources retrieved — document may not cover this topic."
            })
            continue

        # Build context string from retrieved chunks
        context = "\n\n---\n\n".join([
            f"[{s['source']} | Page {s['page']}]\n{s['snippet']}"
            for s in sources
        ])

        # Step 2: Faithfulness score
        faith_score, faith_reason = llm_score(
            FAITHFULNESS_PROMPT.format(context=context, answer=answer),
            client
        )

        # Step 3: Context Relevance score
        relev_score, relev_reason = llm_score(
            RELEVANCE_PROMPT.format(question=question, context=context),
            client
        )

        faithfulness_total += faith_score
        relevance_total += relev_score

        q_short = question[:44] + ("…" if len(question) > 44 else "")
        print(f"  {q_short:<45} {faith_score:>13.2f} {relev_score:>12.2f}")
        print(f"    └ Faithfulness: {faith_reason}")
        print(f"    └ Relevance:    {relev_reason}\n")

        results.append({
            "question": question,
            "answer": answer,
            "sources": [{"source": s["source"], "page": s["page"], "reranked": s.get("reranked", False)} for s in sources],
            "faithfulness_score": round(faith_score, 4),
            "faithfulness_reason": faith_reason,
            "relevance_score": round(relev_score, 4),
            "relevance_reason": relev_reason
        })

    # Aggregate scores
    n = len([r for r in results if r.get("faithfulness_score") is not None])
    if n > 0:
        avg_faith = faithfulness_total / n
        avg_relev = relevance_total / n
        print(f"{'='*80}")
        print(f"  📊 AGGREGATE RESULTS ({n} evaluated questions)")
        print(f"     Average Faithfulness  : {avg_faith:.4f} / 1.0")
        print(f"     Average Relevance     : {avg_relev:.4f} / 1.0")
        print(f"     Combined RAG Score    : {(avg_faith + avg_relev) / 2:.4f} / 1.0")
        print(f"{'='*80}\n")

        # Save results
        output = {
            "metadata": {
                "llm_model": GROQ_MODEL,
                "reranker_active": status.get("reranker_active", False),
                "reranker_model": status.get("reranker_model"),
                "retrieval_k": status.get("retrieval_k", 20),
                "reranked_top_k": status.get("reranked_top_k", 4),
                "total_chunks_indexed": status.get("total_chunks", 0)
            },
            "summary": {
                "num_evaluated": n,
                "avg_faithfulness": round(avg_faith, 4),
                "avg_relevance": round(avg_relev, 4),
                "combined_rag_score": round((avg_faith + avg_relev) / 2, 4)
            },
            "results": results
        }

        output_path = os.path.join(os.path.dirname(__file__), "evaluate_results.json")
        with open(output_path, "w") as f:
            json.dump(output, f, indent=2)
        print(f"  💾 Full results saved to: evaluate_results.json")


if __name__ == "__main__":
    evaluate()
